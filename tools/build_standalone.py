"""Bundle index.html + css + js into one self-contained file, sky-hopper.html.

The single file works no matter how it's opened (from inside a ZIP, emailed,
copied to a USB stick). Re-run this after changing any game file:

    python3 tools/build_standalone.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
html = (root / "index.html").read_text(encoding="utf-8")

def inline_css(match):
    css = (root / match.group(1)).read_text(encoding="utf-8")
    return f"<style>\n{css}</style>"

def inline_js(match):
    js = (root / match.group(1)).read_text(encoding="utf-8")
    return f"<script>\n{js}</script>"

html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', inline_css, html)
html = re.sub(r'<script src="([^"]+)"></script>', inline_js, html)
html = html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by tools/build_standalone.py from index.html, css/ and js/. Edit those, not this file. -->", 1)

(root / "sky-hopper.html").write_text(html, encoding="utf-8")
print("Wrote sky-hopper.html")
